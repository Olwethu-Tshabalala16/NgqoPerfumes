"""Generate public frontend configuration before Vercel's Django build.

Vercel's native Django integration runs collectstatic and serves STATIC_ROOT
through its CDN. This script only creates config.js; it intentionally does not
run collectstatic, connect to the database, or copy a second static output.
"""

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
CONFIG_FILE = FRONTEND / "config.js"


def main():
    if not (FRONTEND / "index.html").is_file():
        raise SystemExit(
            "NgqoPerfumes build failed: frontend/index.html was not found. "
            "Check the Vercel Root Directory setting."
        )

    supabase_url = os.getenv("SUPABASE_URL", "").strip().rstrip("/")
    bucket = os.getenv("SUPABASE_STORAGE_BUCKET", "product-images").strip()
    bucket = bucket or "product-images"

    catalogue_url = ""
    if supabase_url:
        catalogue_url = (
            f"{supabase_url}/storage/v1/object/public/"
            f"{bucket}/catalogue/products.json"
        )

    is_vercel = any(
        os.getenv(name)
        for name in ("VERCEL", "VERCEL_URL", "VERCEL_ENV")
    )
    configuration = {
        "CATALOGUE_JSON_URL": catalogue_url,
        # In production the frontend and API share one origin. Locally, the
        # static frontend runs on port 5500 and Django runs on port 8000.
        "API_BASE_URL": "" if is_vercel else "http://127.0.0.1:8000",
    }

    CONFIG_FILE.write_text(
        "/* Generated by scripts/build_vercel.py; do not add secrets here. */\n"
        "window.NGQO_CONFIG = "
        + json.dumps(configuration, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print("NgqoPerfumes frontend configuration generated.")
    print(f"Supabase catalogue configured: {bool(catalogue_url)}")


if __name__ == "__main__":
    main()
